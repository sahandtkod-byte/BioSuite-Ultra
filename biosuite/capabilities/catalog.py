def _split_id(capability_id: str) -> Tuple[str, str]:
    module, _, function = capability_id.partition(".")
    if not module or not function or "." in function:
        raise ValueError(f"malformed capability id: {capability_id!r}")
    return module, function


def _build(row) -> Capability:
    capability_id, summary, mcp_exposed, interfaces, tools, packages = row
    module, function = _split_id(capability_id)
    return Capability(
        id=capability_id,
        module=module,
        function=function,
        summary=summary,
        implementation=f"{module}:{function}",
        mcp_exposed=mcp_exposed,
        interfaces=interfaces,
        requires_tools=tools,
        requires_packages=packages,
    )


def _index(rows) -> dict:
    index = {}
    for row in rows:
        if row[0] in index:
            raise ValueError(f"duplicate capability id: {row[0]!r}")
        index[row[0]] = row
    return index


_ROW_INDEX = _index(_RAW_ROWS)


def list_capabilities() -> Tuple[Capability, ...]:
    """All catalogued capabilities, in deterministic catalog order.

    Callers get freshly built, frozen Capability objects in a new tuple, so
    no returned structure can mutate catalog state.
    """
    return tuple(_build(row) for row in _RAW_ROWS)


def get_capability(capability_id: str) -> Capability:
    """Return the capability with exactly ``capability_id``.

    Unknown IDs raise ``KeyError``; a non-string ID raises ``TypeError``.
    """
    if not isinstance(capability_id, str):
        raise TypeError(
            f"capability id must be a string, got {type(capability_id).__name__}"
        )
    if capability_id not in _ROW_INDEX:
        raise KeyError(f"unknown capability id: {capability_id!r}")
    return _build(_ROW_INDEX[capability_id])
